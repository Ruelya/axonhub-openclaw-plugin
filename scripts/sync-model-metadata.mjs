#!/usr/bin/env node
/**
 * Generate model-metadata.generated.ts from the curated source JSON.
 *
 * This script reads model-metadata.source.json, validates the schema,
 * normalizes and sorts all objects/arrays deterministically, and writes
 * model-metadata.generated.ts ONLY when the output bytes change. The generated
 * file never contains instance-specific data, credentials, absolute paths, or
 * nondeterministic timestamps.
 *
 * Usage:
 *   npm run sync:model-metadata            # regenerate from source.json
 *   npm run sync:model-metadata --fetch    # fetch from pinned URL, update source.json, regenerate
 *   npm run check:model-metadata           # fail if regeneration would change output
 *
 * Design.md § 1: Model metadata index.
 * Implement.md § 3: Add the upstream metadata generator script.
 */

import { readFileSync, writeFileSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);

// Source and generated artifact live at the package root, one level up from
// this script's `scripts/` directory.
const REPO_ROOT = resolve(__dirname, "..");
const SOURCE_PATH = resolve(REPO_ROOT, "model-metadata.source.json");
const OUTPUT_PATH = resolve(REPO_ROOT, "model-metadata.generated.ts");

// Pinned upstream model-catalog endpoint. This is the single, clearly-marked
// source constant. The runtime never fetches it; only `--fetch` (developer
// command / scheduled CI) reads it to refresh the curated source snapshot.
//
// ASSUMPTION: models.dev publishes an aggregated, provider-keyed JSON catalog
// at this URL. It does NOT expose "which AxonHub protocol endpoint" a model
// uses, so protocol-family routing stays human-curated in the source snapshot.
// `--fetch` only refreshes advisory reasoning hints for records that already
// exist by id; it never invents protocol families. See report notes.
const PINNED_UPSTREAM_URL = "https://models.dev/api.json";
const FETCH_TIMEOUT_MS = 20000;

// Schema validation
function validateSource(data) {
  if (typeof data !== "object" || data === null) {
    throw new Error("Source must be an object");
  }
  if (typeof data.schemaVersion !== "number" || data.schemaVersion !== 1) {
    throw new Error("Source schemaVersion must be 1");
  }
  if (!data.source || typeof data.source.url !== "string") {
    throw new Error("Source must have source.url");
  }
  if (!Array.isArray(data.records)) {
    throw new Error("Source must have records array");
  }

  const validProtocols = ["gemini", "anthropic", "openai-responses", "openai-completions"];
  for (const rec of data.records) {
    if (typeof rec.id !== "string" || !rec.id.trim()) {
      throw new Error(`Record missing id: ${JSON.stringify(rec)}`);
    }
    if (typeof rec.protocolFamily !== "string" || !validProtocols.includes(rec.protocolFamily)) {
      throw new Error(`Record ${rec.id} has invalid protocolFamily: ${rec.protocolFamily}`);
    }
    if (rec.owners && !Array.isArray(rec.owners)) {
      throw new Error(`Record ${rec.id} owners must be array`);
    }
    if (rec.supportedReasoningEfforts && !Array.isArray(rec.supportedReasoningEfforts)) {
      throw new Error(`Record ${rec.id} supportedReasoningEfforts must be array`);
    }
  }

  return true;
}

// Deterministic sort and normalization
function normalizeSource(data) {
  const normalized = {
    schemaVersion: data.schemaVersion,
    source: data.source,
    ownerProtocolFamilies: {},
    ownerAliases: {},
    records: [],
  };

  // Sort owner maps by key
  if (data.ownerProtocolFamilies) {
    const keys = Object.keys(data.ownerProtocolFamilies).sort();
    for (const k of keys) {
      normalized.ownerProtocolFamilies[k] = data.ownerProtocolFamilies[k];
    }
  }
  if (data.ownerAliases) {
    const keys = Object.keys(data.ownerAliases).sort();
    for (const k of keys) {
      normalized.ownerAliases[k] = data.ownerAliases[k];
    }
  }

  // Sort records by id, normalize arrays
  const sorted = [...data.records].sort((a, b) => a.id.localeCompare(b.id));
  for (const rec of sorted) {
    const norm = {
      id: rec.id,
      ...(rec.aliases ? { aliases: [...rec.aliases].sort() } : {}),
      ...(rec.owners ? { owners: [...rec.owners].sort() } : {}),
      protocolFamily: rec.protocolFamily,
      ...(rec.supportedReasoningEfforts
        ? { supportedReasoningEfforts: [...rec.supportedReasoningEfforts] }
        : {}),
      ...(rec.defaultReasoningEffort ? { defaultReasoningEffort: rec.defaultReasoningEffort } : {}),
    };
    normalized.records.push(norm);
  }

  return normalized;
}

// Generate the TypeScript output
function generateOutput(normalized) {
  const header = `// @generated by scripts/sync-model-metadata (npm run sync:model-metadata)
//
// DO NOT EDIT BY HAND. This artifact is a deterministic, byte-stable snapshot
// of the protocol/reasoning enrichment metadata the plugin uses to route
// AxonHub models to the correct OpenClaw \`api\` adapter and reasoning profile.
//
// It contains only the fields the plugin needs. It never contains
// instance-specific data, credentials, or nondeterministic timestamps. Every
// object and array is sorted so an unchanged upstream source produces
// byte-identical output.
//
// The runtime never fetches the upstream catalog directly; releases stay
// reproducible. The resolver in \`model-metadata.ts\` consumes this artifact.

import type { AxonhubProtocolFamily } from "./model-types.js";

/** Schema version for the generated artifact. Bump when the shape changes. */
export const MODEL_METADATA_SCHEMA_VERSION = ${normalized.schemaVersion} as const;

/**
 * A single enrichment record. Keyed by canonical model id; \`owners\` narrows the
 * match so ambiguous global ids do not steal routing from the wrong owner.
 */
export type ModelMetadataRecord = {
  /** Canonical, lowercased model id. */
  id: string;
  /** Known alias ids (lowercased, sorted) that map to this record. */
  aliases?: readonly string[];
  /** Owner/\`owned_by\` values (lowercased, sorted) this record applies to. */
  owners?: readonly string[];
  /** Resolved protocol family. */
  protocolFamily: AxonhubProtocolFamily;
  /** Supported reasoning efforts (sorted by rank), when known. */
  supportedReasoningEfforts?: readonly string[];
  /** Default reasoning effort, when the upstream source specifies one. */
  defaultReasoningEffort?: string;
};

/**
 * Owner-alias groups: AxonHub \`owned_by\` value → protocol family. Used as a
 * narrow owner-level fallback (precedence step 4) before the conservative
 * OpenAI-compatible default. Sorted by owner for determinism.
 */
export const OWNER_PROTOCOL_FAMILIES: Readonly<
  Record<string, AxonhubProtocolFamily>
> = ${JSON.stringify(normalized.ownerProtocolFamilies, null, 2)};

/**
 * Owner aliases: upstream \`owned_by\` variants normalized to a canonical owner
 * key used by \`OWNER_PROTOCOL_FAMILIES\`. Sorted by alias for determinism.
 */
export const OWNER_ALIASES: Readonly<Record<string, string>> = ${JSON.stringify(normalized.ownerAliases, null, 2)};

// Records are sorted by id. Reasoning efforts follow OpenClaw rank order:
// off < minimal < low < medium < high < adaptive < xhigh < max.
export const MODEL_METADATA_RECORDS: readonly ModelMetadataRecord[] = ${JSON.stringify(normalized.records, null, 2)};
`;

  return header;
}

// Fetch upstream catalog and merge reasoning hints into the curated source.
// Protocol-family routing decisions remain human-curated; `--fetch` only
// refreshes advisory reasoning-effort hints for records that already exist.
async function fetchAndMergeUpstream(sourceData) {
  console.log(`Fetching ${PINNED_UPSTREAM_URL}...`);

  const controller = new AbortController();
  const timeout = setTimeout(() => controller.abort(), FETCH_TIMEOUT_MS);

  try {
    const response = await fetch(PINNED_UPSTREAM_URL, {
      signal: controller.signal,
      headers: { Accept: "application/json" },
    });
    clearTimeout(timeout);

    if (!response.ok) {
      throw new Error(`HTTP ${response.status}: ${response.statusText}`);
    }

    const upstreamData = await response.json();

    // Parse known fields conservatively. The upstream schema is not under
    // plugin control, so tolerate missing/unknown fields gracefully.
    const upstreamModels = Array.isArray(upstreamData.models)
      ? upstreamData.models
      : Array.isArray(upstreamData.data)
      ? upstreamData.data
      : Array.isArray(upstreamData)
      ? upstreamData
      : [];

    console.log(`Fetched ${upstreamModels.length} upstream model entries.`);

    // Build id → reasoning hints map
    const hintsMap = new Map();
    for (const m of upstreamModels) {
      if (!m.id || typeof m.id !== "string") continue;
      const id = m.id.toLowerCase().replace(/^axonhub\//, "");

      // Parse reasoning-effort hints from upstream capabilities, if present
      const caps = m.capabilities || {};
      const efforts =
        caps.reasoning_efforts ||
        caps.reasoning_effort_levels ||
        caps.effort_levels ||
        caps.reasoning_levels;

      if (Array.isArray(efforts) && efforts.length > 0) {
        hintsMap.set(id, efforts.filter((e) => typeof e === "string"));
      }
    }

    console.log(`Extracted reasoning hints for ${hintsMap.size} models.`);

    // Merge hints into existing records (keep curated protocol-family decisions)
    let merged = 0;
    for (const rec of sourceData.records) {
      const id = rec.id.toLowerCase();
      const upstreamHints = hintsMap.get(id);
      if (upstreamHints && upstreamHints.length > 0) {
        rec.supportedReasoningEfforts = upstreamHints;
        merged++;
      }
    }

    console.log(`Merged reasoning hints into ${merged} curated records.`);

    // Write updated source.json atomically
    const updatedSource = JSON.stringify(sourceData, null, 2) + "\n";
    writeFileSync(SOURCE_PATH, updatedSource, "utf8");
    console.log(`✅ Updated ${SOURCE_PATH}`);

    return sourceData;
  } catch (err) {
    clearTimeout(timeout);
    console.error(`⚠ Fetch failed: ${err.message}`);
    console.error("Continuing with existing curated source (no merge).");
    return sourceData;
  }
}

// Main
async function main() {
  const args = process.argv.slice(2);
  const shouldFetch = args.includes("--fetch");
  const checkOnly = args.includes("--check");

  // Read and validate source
  const sourceText = readFileSync(SOURCE_PATH, "utf8");
  let sourceData = JSON.parse(sourceText);
  validateSource(sourceData);

  // In --fetch mode, refresh advisory reasoning hints from the pinned upstream
  // URL and rewrite the curated source snapshot. Protocol-family routing stays
  // human-curated. A fetch failure leaves the source untouched (no bad diff).
  if (shouldFetch) {
    sourceData = await fetchAndMergeUpstream(sourceData);
    validateSource(sourceData);
  }

  // Normalize and generate
  const normalized = normalizeSource(sourceData);
  const output = generateOutput(normalized);

  if (checkOnly) {
    const existing = readFileSync(OUTPUT_PATH, "utf8");
    if (existing !== output) {
      console.error("❌ model-metadata.generated.ts is out of sync.");
      console.error("   Run `npm run sync:model-metadata` to regenerate.");
      process.exit(1);
    }
    console.log("✅ model-metadata.generated.ts is up to date.");
    process.exit(0);
  }

  // Write only if changed
  let existing = "";
  try {
    existing = readFileSync(OUTPUT_PATH, "utf8");
  } catch {
    // File doesn't exist yet
  }

  if (existing === output) {
    console.log("✅ model-metadata.generated.ts unchanged.");
  } else {
    writeFileSync(OUTPUT_PATH, output, "utf8");
    console.log("✅ Wrote model-metadata.generated.ts");
  }
}

main().catch((err) => {
  console.error("Generation failed:", err);
  process.exit(1);
});
